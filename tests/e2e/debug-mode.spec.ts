import { expect, test } from "@playwright/test";
import { advanceDialogue, startNewGame, setDialogueSpeed } from "./helpers";

test("debug scenes and reload do not change the ordinary game, learning or settings", async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  await page.setViewportSize({ width: 360, height: 780 });
  await startNewGame(page);
  await page.evaluate(() => {
    localStorage.setItem("dreamscape.learning.v1", JSON.stringify({ schemaVersion: 1, revision: 0, alwaysTranslate: false, revealed: {}, marks: {}, records: {}, openQuestion: null, openTopic: null }));
    localStorage.setItem("dreamscape.presentation.v1", JSON.stringify({ schemaVersion: 1, confirmChoices: true, reduceMotion: false }));
  });
  const original = await page.evaluate(() => Object.fromEntries(Object.entries(localStorage)));
  await page.goto("/?debug");
  await expect(page.getByTestId("debug-panel")).toBeVisible();
  await expect(page.getByTestId("debug-city")).toHaveValue("milano");
  await expect(page.getByTestId("debug-city").locator("option")).toHaveCount(4);
  await page.screenshot({ path: testInfo.outputPath("debug-panel.png"), fullPage: true });
  await page.getByTestId("debug-target").selectOption("duomo_milano");
  await page.getByRole("button", { name: "この場面を開く" }).click();
  await expect(page.getByTestId("tourism-guide")).toBeVisible();
  await expect(page.getByRole("heading", { name: "ミラノ大聖堂（ドゥオモ）", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "設定へ戻る" }).click();
  await page.getByTestId("debug-scene").selectOption("battle");
  await page.getByTestId("debug-target").selectOption("milano_duomo_01");
  await page.getByTestId("debug-ap").fill("8");
  await page.getByTestId("debug-affection").fill("3");
  await page.getByRole("button", { name: "この場面を開く" }).click();
  await expect(page.getByTestId("debug-session")).toContainText("通常セーブとは別");
  await expect(page.getByTestId("battle-location")).toContainText("ドゥオモ");
  await page.screenshot({ path: testInfo.outputPath("debug-battle.png") });
  await page.getByRole("button", { name: "設定", exact: true }).click();
  await page.getByLabel("演出を短縮する").check();
  await page.getByLabel("常に日本語訳を表示する").check();
  await page.getByRole("button", { name: "閉じる", exact: true }).click();
  await setDialogueSpeed(page, "0");
  await advanceDialogue(page);
  await page.getByRole("button", { name: "設定へ戻る" }).click();
  await page.getByTestId("debug-scene").selectOption("encounter");
  await page.getByTestId("debug-target").selectOption("galleria_fortune");
  await page.getByRole("button", { name: "この場面を開く" }).click();
  await expect(page.getByTestId("encounter-screen")).toBeVisible();
  await expect(page.getByTestId("debug-place")).toContainText("ガッレリア");
  await expect(page.getByTestId("encounter-screen").locator(".encounter-background")).toHaveAttribute("src", /galleria/);
  await page.getByRole("button", { name: "設定へ戻る" }).click();
  await page.getByTestId("debug-scene").selectOption("date");
  await page.getByTestId("debug-target").selectOption("milano_brera_date_01");
  for (const [roll, reaction] of [["positive", "次がある言い方だもんね"], ["negative", "本当は続いてほしいときほど"]] as const) {
    await page.getByTestId("debug-roll").selectOption(roll);
    await page.getByRole("button", { name: "この場面を開く" }).click();
    const scene = page.getByTestId("romance-scene");
    await expect(scene).toBeVisible();
    await setDialogueSpeed(page, "0");
    for (let step = 0; !(await scene.locator(".choice").count()); step++) {
      expect(step).toBeLessThan(50);
      await advanceDialogue(page);
    }
    await scene.locator(".choice").nth(2).click();
    await expect(scene).toContainText(reaction);
    await page.getByRole("button", { name: "設定へ戻る" }).click();
  }
  await page.getByTestId("debug-scene").selectOption("tourism");
  await page.getByTestId("debug-target").selectOption("duomo_milano");
  await page.getByRole("button", { name: "この場面を開く" }).click();
  await page.getByRole("button", { name: "設定", exact: true }).click();
  await page.getByRole("button", { name: "Debug用の一時データの消去" }).click();
  await expect(page.getByRole("heading", { name: "Debug用の一時データを消去しますか？" })).toBeVisible();
  await expect(page.getByText("通常のセーブ・英語ノート・表示設定は消去しません。", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "消去せず戻る" }).click();
  expect(await page.evaluate(() => Object.fromEntries(Object.entries(localStorage)))).toEqual(original);
  await page.getByRole("button", { name: "設定", exact: true }).click();
  await page.getByRole("button", { name: "Debug用の一時データの消去" }).click();
  await page.getByRole("button", { name: "Debug用の一時データを消去する" }).click();
  await expect(page.getByTestId("debug-panel")).toBeVisible();
  await page.reload();
  await expect(page.getByTestId("debug-panel")).toBeVisible();
  expect(await page.evaluate(() => Object.fromEntries(Object.entries(localStorage)))).toEqual(original);
  await page.getByRole("link", { name: "背景・人物・表情を確認" }).click();
  await expect(page.getByTestId("character-preview")).toBeVisible();
  await page.getByTestId("preview-background").selectOption("milano_brera_case");
  await page.getByTestId("preview-emotion").selectOption("exasperated");
  await expect(page.getByTestId("preview-stage").locator(".vn-background")).toBeVisible();
  await page.getByRole("link", { name: "Debugへ戻る" }).click();
  await page.getByRole("link", { name: "通常プレイに戻る" }).click();
  expect(await page.evaluate(() => Object.fromEntries(Object.entries(localStorage)))).toEqual(original);
});
